        }
    }

    buildTypes {
        release {
            // android/key.properties + upload-keystore.jks (not in git; back them up — updates need the same key).
            signingConfig = if (keystore.isNotEmpty()) signingConfigs.getByName("release") else signingConfigs.getByName("debug")
        }
    }
